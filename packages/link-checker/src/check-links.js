#!/usr/bin/env node
/*
 * 失效链接检测 workflow — 1:1 port of HSJ scan_links.py + create_link_issues.py
 *
 * 功能:
 *   1. 从 link-checker-config.yaml 读取社区配置
 *   2. 逐社区: clone → 扫描源码提取 URL → HTTP HEAD/GET 检测 → 按分组模式提 issue
 *
 * 用法:
 *   node check-links.js [--config=<path>] [--community=<name>] [--all-communities] [--dryRun]
 *
 * 环境变量:
 *   ATOMGIT_TOKEN   AtomGit/GitCode token (clone + issue)
 */

import fs from 'fs';
import path, { dirname } from 'path';
import { fileURLToPath } from 'url';
import { parse as parseYaml } from 'yaml';
import { log, parseArgs, createIssue, findAllIssuesByTitlePrefix, updateIssue, addIssueComment } from '@geo-workflow/core';
import {
  findCodeFiles,
  extractLinksFromFile,
  filterExcludedUrls,
  scanConcurrently,
  cloneRepo,
} from './link-scanner.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../../..');
const DEFAULT_CONFIG = path.join(REPO_ROOT, 'link-checker-config.yaml');
const ISSUE_TITLE_PREFIX = '[LinkChecker]';

// ── Config loading (1:1 port of load_community_config) ──

function loadConfig(configPath) {
  if (!fs.existsSync(configPath)) {
    throw new Error(`Config not found: ${configPath}`);
  }
  const raw = fs.readFileSync(configPath, 'utf-8');
  const cfg = parseYaml(raw);
  return cfg.communities || {};
}

// ── Grouping (1:1 port of group_broken_links) ──

function groupBrokenLinks(brokenLinks, groupBy = 'file', statusCodes = null) {
  let filtered = brokenLinks;
  if (statusCodes) {
    filtered = brokenLinks.filter(link => {
      const code = String(link.status_code || 'unknown');
      return statusCodes.has(code);
    });
  }

  const groups = new Map();
  for (const link of filtered) {
    let key;
    if (groupBy === 'all') {
      key = 'all-broken-links';
    } else if (groupBy === 'status') {
      key = String(link.status_code || 'unknown');
    } else if (groupBy === 'domain') {
      try {
        const parsed = new URL(link.url);
        key = parsed.hostname || 'unknown';
      } catch {
        key = 'unknown';
      }
    } else {
      key = link.file_path || 'unknown';
    }
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(link);
  }
  return groups;
}

// ── Issue body (1:1 port of build_issue_body) ──

function buildIssueBody(groupKey, links, community, scanDate, domain) {
  const lines = [
    `## Link Checker Report — ${community}`,
    '',
    `**Scan date**: ${scanDate}`,
    `**Domain**: ${domain}`,
    `**Group**: \`${groupKey}\``,
    `**Broken links**: ${links.length}`,
    '',
    '---',
    '',
    '| Status | URL | File | Line | Error |',
    '|--------|-----|------|------|-------|',
  ];

  const sorted = [...links].sort((a, b) => {
    const fa = a.file_path || '';
    const fb = b.file_path || '';
    if (fa !== fb) return fa.localeCompare(fb);
    return (a.line_number || 0) - (b.line_number || 0);
  });

  for (const link of sorted) {
    const status = link.status_code || '—';
    const url = link.url || '';
    const filePath = link.file_path || '';
    const lineNum = link.line_number || '';
    let error = link.error || '—';
    if (error.length > 60) error = error.slice(0, 57) + '...';
    lines.push(`| ${status} | \`${url}\` | \`${filePath}\` | ${lineNum} | ${error} |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('### Suggested Actions');
  lines.push('');
  lines.push('1. Verify each URL above and update or remove broken links');
  lines.push('2. For relative paths, ensure the target page exists in the repository');
  lines.push('3. For external URLs, check if the target has moved or been removed');
  lines.push('');
  lines.push('> Auto-generated by Link Checker');

  return lines.join('\n');
}

// ── Issue title (1:1 port of build_issue_title) ──

function buildIssueTitle(community, groupKey, count, groupBy = 'file') {
  const dateStr = new Date().toISOString().slice(0, 10);
  if (groupBy === 'all') {
    return `${ISSUE_TITLE_PREFIX}[${community}] ${count} broken link(s) (${dateStr})`;
  } else if (groupBy === 'status') {
    return `${ISSUE_TITLE_PREFIX}[${community}] ${count} broken link(s) with HTTP ${groupKey} (${dateStr})`;
  } else {
    return `${ISSUE_TITLE_PREFIX}[${community}] ${count} broken link(s) in ${groupKey} (${dateStr})`;
  }
}

// ── Issue creation (1:1 port of create_issue + createOrUpdate) ──

async function createOrUpdateIssue(owner, repo, title, body, { dryRun = false } = {}) {
  if (dryRun) {
    log(`[dryRun] Would create/update: ${title}`);
    return { url: 'dry-run', action: 'dryRun' };
  }

  const existing = await findAllIssuesByTitlePrefix({ owner, repo, prefix: ISSUE_TITLE_PREFIX, state: 'open' });
  const match = existing.find(e => e.title === title);

  if (match) {
    log(`Updating existing issue #${match.number}`);
    await updateIssue({ owner, repo, issue_number: match.number, title, body });
    return { url: match.html_url, action: 'updated' };
  }

  log(`Creating new issue: ${title}`);
  const result = await createIssue({ owner, repo, title, body });
  return { url: result.html_url || '', action: 'created' };
}

// ── Close old issues with no findings ──

async function closeOldIssues(owner, repo, usedTitles, { dryRun = false } = {}) {
  if (dryRun) return;
  const existing = await findAllIssuesByTitlePrefix({ owner, repo, prefix: ISSUE_TITLE_PREFIX, state: 'open' });
  for (const issue of existing) {
    if (!usedTitles.has(issue.title)) {
      log(`Closing stale issue #${issue.number}`);
      try {
        await addIssueComment({ owner, repo, issue_number: issue.number, body: '/close' });
      } catch (err) {
        log(`Failed to close issue #${issue.number}: ${err.message}`);
      }
    }
  }
}

// ── Single community run (1:1 port of main flow in scan_links.py + create_link_issues.py) ──

async function runCommunity(name, cfg, { dryRun = false }) {
  log(`\n========== Community: ${name} ==========`);

  const {
    repo_url: repoUrl,
    domain: rawDomain,
    branch = 'main',
    exclude_files: excludeFiles = [],
    exclude_domains: excludeDomains = [],
    exclude_urls: excludeUrls = [],
    url_prefix: urlPrefix = '',
    deduplicate_level: deduplicateLevel = 'file',
    issue_repo_owner: issueOwner = '',
    issue_repo_name: issueName = '',
    issue_repo_platform: issuePlatform = '',
    issue_group_by: groupBy = 'all',
    issue_status_codes: statusCodesStr = '',
  } = cfg;

  if (!repoUrl) {
    log(`ERROR: ${name} missing repo_url`);
    return { name, ok: false, error: 'missing repo_url' };
  }
  if (!rawDomain) {
    log(`ERROR: ${name} missing domain`);
    return { name, ok: false, error: 'missing domain' };
  }

  const domain = rawDomain.replace(/\/+$/, '');

  log(`Scanning: ${repoUrl} (branch: ${branch})`);
  log(`Domain: ${domain}`);
  log(`URL prefix: ${urlPrefix}`);
  log(`Excludes: ${excludeFiles}`);
  log(`Exclude domains: ${excludeDomains}`);
  log(`Exclude URLs: ${excludeUrls}`);

  // 1. Clone
  let baseDir;
  try {
    baseDir = cloneRepo(repoUrl, branch);
  } catch (err) {
    return { name, ok: false, error: err.message };
  }

  // 2. Find code files
  const files = findCodeFiles(baseDir, excludeFiles);
  log(`Found ${files.length} code files`);

  // 3. Extract links (1:1 port of extract_links_from_file loop)
  let allLinks = [];
  for (const f of files) {
    allLinks.push(...extractLinksFromFile(f, baseDir, domain, excludeFiles, excludeDomains, urlPrefix));
  }
  log(`Extracted ${allLinks.length} links`);

  // 4. Filter excluded URLs
  allLinks = filterExcludedUrls(allLinks, excludeUrls);
  log(`After URL exclusion: ${allLinks.length} links`);

  if (allLinks.length === 0) {
    log(`No links to check for ${name}`);
    // Still close old issues
    if (issueOwner && issueName && !dryRun) {
      await closeOldIssues(issueOwner, issueName, new Set());
    }
    return { name, ok: true, totalLinks: 0, broken: 0, issues: [] };
  }

  // 5. HTTP check (1:1 port of scan_concurrently)
  const workers = cfg.workers || 5;
  const timeout = cfg.timeout || 10;
  const delay = cfg.delay != null ? cfg.delay : 0.5;
  log(`Checking ${allLinks.length} links (${workers} workers, ${delay}s delay)...`);

  const results = await scanConcurrently(allLinks, workers, timeout, delay);
  const okLinks = results.filter(r => r.result === 'ok');
  const brokenLinks = results.filter(r => r.result === 'broken');

  log(`OK: ${okLinks.length}, Broken: ${brokenLinks.length}`);

  const statusCounts = {};
  for (const r of brokenLinks) {
    const code = String(r.status_code || 'unknown');
    statusCounts[code] = (statusCounts[code] || 0) + 1;
  }

  const scanDate = new Date().toISOString();

  // 6. Create issues (1:1 port of create_link_issues.py main)
  const created = [];

  if (brokenLinks.length > 0 && issueOwner && issueName) {
    let statusCodesSet = null;
    if (statusCodesStr) {
      statusCodesSet = new Set(statusCodesStr.split(',').map(s => s.trim()).filter(Boolean));
    }

    const groups = groupBrokenLinks(brokenLinks, groupBy, statusCodesSet);

    if (groups.size === 0) {
      log(`No broken links match the filter criteria.`);
    } else {
      log(`Broken links: ${brokenLinks.length}, Groups: ${groups.size}`);

      const usedTitles = new Set();
      for (const [groupKey, links] of groups) {
        const title = buildIssueTitle(name, groupKey, links.length, groupBy);
        const body = buildIssueBody(groupKey, links, name, scanDate, domain);
        usedTitles.add(title);

        try {
          const result = await createOrUpdateIssue(issueOwner, issueName, title, body, { dryRun });
          created.push({
            group: groupKey,
            title,
            url: result.url,
            broken_count: links.length,
            action: result.action,
          });
          log(`  ${result.action}: ${title}`);
        } catch (err) {
          log(`ERROR: Failed to create issue for ${groupKey}: ${err.message}`);
        }
      }

      // Close stale issues
      if (!dryRun) {
        await closeOldIssues(issueOwner, issueName, usedTitles);
      }
    }
  } else if (brokenLinks.length === 0 && issueOwner && issueName) {
    log(`No broken links found for ${name}`);
    if (!dryRun) {
      await closeOldIssues(issueOwner, issueName, new Set());
    }
  }

  // 7. Output JSON summary (1:1 port of scan_links.py output)
  const output = {
    community: name,
    scan_date: scanDate,
    domain,
    total_files: files.length,
    total_links: results.length,
    broken_links: brokenLinks,
    ok_links_count: okLinks.length,
    summary: {
      total: results.length,
      ok: okLinks.length,
      broken: brokenLinks.length,
      broken_by_status: statusCounts,
    },
    issues_created: created.length,
    issues: created,
  };

  // Write JSON output file
  const outputDir = path.join(REPO_ROOT, 'link-checker-results');
  fs.mkdirSync(outputDir, { recursive: true });
  const outputFile = path.join(outputDir, `${name}-${scanDate.slice(0, 10)}.json`);
  fs.writeFileSync(outputFile, JSON.stringify(output, null, 2), 'utf-8');
  log(`Results saved to ${outputFile}`);

  // Cleanup temp dir
  try {
    fs.rmSync(baseDir, { recursive: true, force: true });
  } catch {}

  return {
    name,
    ok: true,
    totalLinks: results.length,
    broken: brokenLinks.length,
    issues: created,
  };
}

// ── Main (1:1 port of run.py cmd_link_check) ──

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const configPath = args.config ? path.resolve(args.config) : DEFAULT_CONFIG;
  const dryRun = args.dryRun || false;
  const allCommunities = args.allCommunities || false;
  const communityFilter = args.community || null;

  log(`Config: ${configPath}`);
  log(`Mode: ${dryRun ? 'dry-run' : 'normal'}`);

  let communities;
  try {
    communities = loadConfig(configPath);
  } catch (err) {
    log(`ERROR: ${err.message}`);
    process.exit(1);
  }

  const communityNames = Object.keys(communities);
  if (communityNames.length === 0) {
    log(`ERROR: No communities in config`);
    process.exit(1);
  }

  let targets;
  if (allCommunities) {
    targets = communityNames;
  } else if (communityFilter) {
    if (!communities[communityFilter]) {
      log(`ERROR: Community '${communityFilter}' not found. Available: ${communityNames.join(', ')}`);
      process.exit(1);
    }
    targets = [communityFilter];
  } else {
    log(`Specify --community=<name> or --all-communities`);
    process.exit(1);
  }

  log(`Communities: ${targets.join(', ')}`);

  const summaries = [];
  for (const name of targets) {
    try {
      summaries.push(await runCommunity(name, communities[name], { dryRun }));
    } catch (err) {
      log(`ERROR ${name}: ${err.message}`);
      summaries.push({ name, ok: false, error: err.message });
    }
  }

  log(`\n===== Summary =====`);
  const failed = summaries.filter(s => !s.ok);
  log(`Total: ${summaries.length}  OK: ${summaries.length - failed.length}  Failed: ${failed.length}`);
  for (const s of summaries) {
    if (s.ok) {
      log(`  ✅ ${s.name}  links: ${s.totalLinks || 0}  broken: ${s.broken || 0}  issues: ${s.issues?.length || 0}`);
    } else {
      log(`  ❌ ${s.name}  ${s.error || ''}`);
    }
  }
}

main().catch(err => {
  console.error(`ERROR: ${err.message}`);
  process.exit(1);
});
